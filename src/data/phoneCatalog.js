function createPhoneImage(name, accentA, accentB) {
  const lines = name.split(" ");
  const topLine = lines.slice(0, 2).join(" ");
  const bottomLine = lines.slice(2).join(" ");

  const svg = `
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 480 640">
      <defs>
        <linearGradient id="g" x1="0" x2="1" y1="0" y2="1">
          <stop offset="0%" stop-color="${accentA}" />
          <stop offset="100%" stop-color="${accentB}" />
        </linearGradient>
      </defs>
      <rect width="480" height="640" rx="44" fill="url(#g)" />
      <rect x="120" y="42" width="240" height="22" rx="11" fill="rgba(255,255,255,0.32)" />
      <rect x="90" y="86" width="300" height="468" rx="34" fill="rgba(255,255,255,0.14)" stroke="rgba(255,255,255,0.35)" />
      <circle cx="158" cy="152" r="34" fill="rgba(255,255,255,0.42)" />
      <circle cx="240" cy="152" r="34" fill="rgba(255,255,255,0.28)" />
      <circle cx="322" cy="152" r="34" fill="rgba(255,255,255,0.18)" />
      <text x="240" y="420" text-anchor="middle" font-size="34" font-family="Segoe UI, Arial, sans-serif" font-weight="700" fill="#ffffff">${topLine}</text>
      <text x="240" y="460" text-anchor="middle" font-size="24" font-family="Segoe UI, Arial, sans-serif" font-weight="600" fill="rgba(255,255,255,0.92)">${bottomLine}</text>
    </svg>
  `;

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

